"""Generate the enlarged world, map and camera drawing paths.

The caller supplies the arena layout, HUD/map interfaces and original callbacks.
Each view preserves the shared projection state and tracks which actor or widget
owns its cached pixels, preventing one view from reusing another view's contents.
"""
import re
from patch_support import asm

CURSOR_STATS = 0x9af4e8
CURSOR_RECT = 0x9af5e8
COMPOSE_BUSY = 0x9aa0e8


def assemble(address, source):
    """Keep the existing local-label and explicit REP-dword assembler dialect."""
    for label in re.findall(r'\b(\w+):', source):
        if label not in ('es', 'ds', 'cs', 'ss'):
            source = re.sub(r'\b' + label + r'\b', 'hud49_' + label, source)
    return asm(
        address,
        source.replace('rep movsd;', '.byte 0xf3,0xa5;').replace('rep stosd;', '.byte 0xf3,0xab;')
    )


