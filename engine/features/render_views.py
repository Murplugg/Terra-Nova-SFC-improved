        f" jne done;"
        f"\n cmp dword ptr [0x446f80],0x01900140;"
        f" jne done;"
        f"\n xor ebx,ebx;"
        f" mov ebp,{hud.SLOTS};"
        f"\n slot: cmp dword ptr [ebp],0;"
