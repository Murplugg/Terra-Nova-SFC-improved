def mode():
    """Low-image VBE transition: preserve the palette across the first native mode switch."""
    return (
        f"cmp byte ptr [0x1d0d449],0x6b;"
        f" je mode_ready;"
        f"\n mov dx,0x3c7;"
        f" xor eax,eax;"
        f" out dx,al;"
        f" add dx,2;"
        f"\n mov edi,0x9aa4e8;"
        f" mov ecx,768;"
        f"\n readpal: in al,dx;"
        f" stosb;"
        f" loop readpal;"
        f"\n mov eax,0x4f02;"
        f" mov ebx,0x4103;"
        f" int 0x10;"
        f"\n mov dx,0x3c8;"
        f" xor eax,eax;"
        f" out dx,al;"
        f" inc dx;"
        f"\n mov esi,0x9aa4e8;"
        f" mov ecx,768;"
        f"\n writepal: lodsb;"
        f" out dx,al;"
        f" loop writepal;"
        f"\n mode_ready:ret;"
    )
