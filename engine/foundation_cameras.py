def invalidate_source():
    return (
        f"\n pushfd;"
        f" push eax;"
        f" cmp eax,3;"
        f" jae done;"
        f"\n shl eax,7;"
        f" mov dword ptr [eax+{SLOTS}],0;"
        f"\n done: pop eax;"
        f" popfd;"
        f" push ebx;"
        f" push ecx;"
        f" push edx;"
        f" push esi;"
        f" push edi;"
        f" jmp 0x274da9;"
        f"\n "
    )


def camera_merge():
    return assemble(MERGE, merge_source())


def cameras():
    """Emit the complete camera foundation, including its optimized compositor."""
    return [
        (ENTRY, assemble(ENTRY, world_source())),
        (PREPARE, assemble(PREPARE, prepare_source())),
        (MERGE, camera_merge()),
        (INVALIDATE, assemble(INVALIDATE, invalidate_source())),
        (0x274da4, branch(0x274da4, INVALIDATE)),
        (0x9ba0e8, fast_compositor(
            prepare=PREPARE, merge=MERGE
        )),
        (0x29edb4, branch(0x29edb4, ENTRY)),
    ]


def initial_data():
    state = bytearray(0x600)
    for i in range(3):
        struct.pack_into('<3I', state, 0x400 + i * 128 + 56, BASES[i], REFS[i], MASKS[i])
    return [(STATE, bytes(state))] + [(a, b'\xa5' * 256) for a in CAM_GUARDS]
