PREPARE = 0x9d9000
INVALIDATE = 0x9d9400
STATE = 0x9dc000
SLOTS = STATE + 0x400
SAVE = STATE + 0x100
CAP = 48000
BASES = (0x9e0100, 0x9ec100, 0x9f8100)
REFS = (0xa05100, 0xa07100, 0xa09100)
MASKS = (0xa0b100, 0xa0d100, 0xa0f100)
CAM_GUARDS = tuple(a for b in BASES for a in (b - 256, b + CAP)
                   ) + tuple(a for b in (*REFS, *MASKS) for a in (b - 256, b + 6400))
# Slot: valid,dirty,ctx,widget,root,logical offset,x,y,w,h,physical x,y,w,h,
# pixels,reference,mask,widget callback/type signature,render count,skip count.


