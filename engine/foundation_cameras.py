"""Capture and compose the three secondary HUD views before native relocation.

Each slot tracks its widget, projection and mirror state so an old camera image
cannot be reused after the panel changes. The merge copies visible runs in bulk
while preserving the explicit drawing mask, including dialog coverage. Original canvas calls
and the displaced widget prologue keep the engine's calling conventions.
"""
import re
import struct
from foundation_hud import LOW, CANVAS, MASK, FRAME, assemble, branch, fast_compositor

