"""Provide the DOS file services needed by the game on Windows.

Guest C:\\TNOVA and D:\\ paths resolve into the supplied game and CD roots.
The game root is writable; the CD root stays read-only. Unsupported service
calls stop with a diagnostic so an unhandled operation cannot silently succeed.
"""
from build_paths import CONFIG
