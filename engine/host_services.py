SEL = 0x1007
ROM = 0x78000
VBE_STATE = 0x1d0b000
FB = 0xe0000000
FB_SIZE = 0x800000
MODES = ((0x101, 640, 480), (0x103, 800, 600))
APIS = ['VirtualAlloc', 'VirtualFree']


def setup(write):
    write(0x1d0ff00, b'\xcf')
    write(0x1d07000, struct.pack('<2I', 0x23, 0x1d0ff00) * 256)
    write(0x1d0e000, struct.pack('<I', 0x78001000) * 256)
    write(ROM + 0x1000, b'\xcf')
    write(ROM, struct.pack('<3H', *[m[0] for m in MODES], 0xffff))
    write(ROM + 16, b'Terra Nova native research host\0')
    for i, (mode, w, h) in enumerate(MODES):
        b = bytearray(256)
        struct.pack_into('<HBBHHHHIHHH', b, 0, 0x99, 7, 0, 64, 64, 0xa000, 0, 0, w, w, h)
        b[22:29] = bytes((8, 16, 1, 8, 1, 4, 0))
        b[29] = min(255, FB_SIZE // (w * h) - 1)
        struct.pack_into('<I', b, 40, FB)
        write(ROM + 0x200 + i * 256, b)


