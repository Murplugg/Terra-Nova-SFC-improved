BDA_BDA = 0x1d0d000


def bda_setup(r, write):
    patches = []
    # These are the high-resolution patch's explicit BDA_BDA mode comparisons.
    needle = bytes.fromhex('803d49040000')
    at = 0x8234e8
    while (at := r.find(needle, at)) >= 0:
        assert at < 0xa234e8, hex(at)
        write(at + 2, struct.pack('<I', BDA_BDA + 0x449))
        patches.append(at + 2)
        at += len(needle)
    assert len(patches) == 21, len(patches)
    for a, old in (
        (0x304fd1, 0x417), (0x305003, 0x41c), (0x305009, 0x41a), (0x30500f, 0x418),
        (0x305018, 0x418)
    ):
        assert r[a:a + 4] == struct.pack('<I', old), hex(a)
        write(a, struct.pack('<I', BDA_BDA + old))
        patches.append(a)
    write(BDA_BDA + 0x449, b'\x03')
    return patches


