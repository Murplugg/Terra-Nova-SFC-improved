PALETTE_CODE = 0x1d25000

PALETTE_STATE = 0x1d0f800


def palette_setup(write, asm, r):
    assert r[0x29e29c:0x29e2a1] == bytes.fromhex('e8a3a00000')
    write(0x29e29c, asm(0x29e29c, f'call {PALETTE_CODE}'))
    write(
        PALETTE_CODE,
        asm(
            PALETTE_CODE, (
                f"\n pushfd;"
                f"pushad;"
                f"\n cmp dword ptr [0x35f8c8],0;"
                f"jne palette_ready;"
                f"\n inc dword ptr [{PALETTE_STATE}];"
                f"call 0x2f1130;"
                f"mov [{PALETTE_STATE+4}],eax;"
                f"\n test eax,eax;"
                f"js palette_failure;"
                f"cmp dword ptr [0x35f8c8],0;"
                f"je palette_failure;"
                f"\n palette_ready:popad;"
                f"popfd;"
                f"jmp 0x2a8344;"
                f"\n palette_failure:mov eax,0xff00;"
                f"int 0x21;"
                f"\n "
            )
        )
    )
