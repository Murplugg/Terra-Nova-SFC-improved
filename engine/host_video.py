        f"jmp io_done;"
        f"\n pic_eoi:cmp al,0x20;"
        f"jne stop;"
        f"inc dword ptr [{STATE+0x1b0}];"
        f"jmp io_done;"
        f"\n io_done:mov eax,[{PORT+16}];"
        f"add [ebp+0xb8],eax;"
        f"popad;"
        f"mov eax,-1;"
        f"ret 4;"
        f"\n native_in8:\n movzx edx,word ptr [ebp+0xa8];"
        f"mov dword ptr [{PORT+16}],1;"
        f"cmp edx,0x3cf;"
        f"je gc_read;"
        f"cmp edx,0x3c9;"
        f"je dac_read;"
